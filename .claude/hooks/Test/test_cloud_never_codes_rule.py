"""
test_cloud_never_codes_rule - rule R39 (code is generated by a local model only) and the new
`local-coder` launcher are WRITTEN where every project reads them (work-ugs-audit, plan 14, R15).

Offline, reads documentation only. R39 must live in `.claude/rules/workflows.md`, inside the
RT-EXPORT region of `.claude/CLAUDE.md` (exported to other projects), in the rule index, in the
agent definition, in the loop-engineer skill and in chapter 11 of the manual. The agent must name
the driver and the audit it runs under R35, and must carry no sentence that lets the wrapper or
the session write, fix or finish code. The older wording (one dispatch per plan, "audits
nothing") must be gone from every definition and every chapter.

Scope, stated rather than hidden: it proves the rule is WRITTEN. It cannot prove a model obeyed
it; the driver's own suite and the review rounds under R35 are what exercise behaviour. Every
finder has its negative control (R20).
"""
import re
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
WORKFLOWS = REPO / ".claude" / "rules" / "workflows.md"
CODE_STYLE = REPO / ".claude" / "rules" / "code-style.md"
TESTING = REPO / ".claude" / "rules" / "testing.md"
CLAUDE_MD = REPO / ".claude" / "CLAUDE.md"
AGENT = REPO / ".claude" / "agents" / "local-coder.md"
LOOP_SKILL = REPO / ".claude" / "skills" / "loop-engineer" / "SKILL.md"
MANUAL = REPO / "docs" / "manual"
CHAPTER = MANUAL / "11-local-coding.md"
AGENTS_CHAPTER = MANUAL / "05-agents.md"
AIDER_CHAPTER = MANUAL / "14-aider-pipeline.md"

MODEL_TAG = re.compile(r"\b[a-z][a-z0-9._-]*:[0-9]+(?:\.[0-9]+)?b\b")
# An imperative that hands code work to the wrapper or the session. A negation just before the
# verb ("never rewrite the code") is a prohibition, not an instruction, and is not reported.
EDIT_INSTRUCTION = re.compile(
    r"\b(?:rewrite|fix|finish|patch|correct|edit|write)\s+(?:the|that|this|any|each|a)\s+"
    r"(?:code|source|module|script|function|implementation)", re.IGNORECASE)
NEGATION = re.compile(r"(?:\bnot\b|\bnever\b|\bno\b|n't)\W*(?:\w+\W+){0,3}$", re.IGNORECASE)
STALE_PHRASES = ("audits nothing", "no audit inside", "There is no audit inside",
                 "One plan is one `local-coder` dispatch", "One plan is one dispatch",
                 "one dispatch per plan")


def flat(text: str) -> str:
    """Collapse whitespace so a phrase wrapped across lines is still found."""
    return re.sub(r"\s+", " ", text)


def block(text: str, start: str, end: str) -> str:
    """The text from a start marker to the next end marker (or the end of the text)."""
    begin = text.index(start)
    stop = text.find(end, begin + len(start))
    return text[begin:stop if stop != -1 else len(text)]


def r39(text: str) -> str:
    """The R39 block of workflows.md, up to the next level-2 heading."""
    return block(text, "**R39", "\n## ")


def export_region(text: str) -> str:
    """The text between the RT-EXPORT markers of .claude/CLAUDE.md."""
    return block(text, "<!-- RT-EXPORT:BEGIN -->", "<!-- RT-EXPORT:END -->")


def edit_instructions(text: str) -> list:
    """Every imperative that asks someone to write or change code and is not a prohibition."""
    found = []
    body = flat(text)
    for match in EDIT_INSTRUCTION.finditer(body):
        if not NEGATION.search(body[max(0, match.start() - 40):match.start()]):
            found.append(match.group(0))
    return found


def stale_phrases(text: str) -> list:
    """Per-plan-dispatch and no-audit wordings that R39 retired."""
    body = flat(text)
    return [phrase for phrase in STALE_PHRASES if phrase in body]


class TestFinders(unittest.TestCase):
    """The finders must be able to fail, or the checks below prove nothing (R20)."""

    def test_an_edit_instruction_is_reported(self):
        self.assertTrue(edit_instructions("Then fix the code and rewrite the module with Edit."))

    def test_a_prohibition_is_not_reported(self):
        self.assertEqual(edit_instructions("The wrapper must never rewrite the code."), [])
        self.assertEqual(edit_instructions("Do NOT edit the source files."), [])

    def test_a_stale_wording_is_reported(self):
        self.assertTrue(stale_phrases("It audits nothing and never commits."))
        self.assertEqual(stale_phrases("It audits the written files under R35."), [])


class TestRuleIsWritten(unittest.TestCase):
    def setUp(self):
        self.workflows = WORKFLOWS.read_text(encoding="utf-8")
        self.claude = CLAUDE_MD.read_text(encoding="utf-8")

    def test_r39_is_named_where_every_project_reads_it(self):
        self.assertIn("**R39", self.workflows)
        self.assertIn("R39", export_region(self.claude))
        self.assertIn("R39", AGENT.read_text(encoding="utf-8"))
        self.assertIn("R39", LOOP_SKILL.read_text(encoding="utf-8"))
        self.assertIn("R39", CHAPTER.read_text(encoding="utf-8"))

    def test_r39_states_the_rule_its_cost_and_its_exemptions(self):
        body = flat(r39(self.workflows))
        for phrase in ("local model", "local-coder", "aider-setup", "[!]", "revised",
                       "context-budget.json", "install.ps1", "data files", "tests included"):
            with self.subTest(phrase=phrase):
                self.assertIn(phrase, body)

    def test_r39_says_the_cloud_writes_no_code(self):
        body = flat(r39(self.workflows))
        self.assertIn("no code", body)
        self.assertIn("cloud", body)
        for role in ("spec", "plans", "progress", "reviews", "memory"):
            with self.subTest(role=role):
                self.assertIn(role, body)

    def test_the_exported_region_carries_the_rule_in_a_few_sentences(self):
        region = flat(export_region(self.claude))
        self.assertIn("R39", region)
        self.assertIn("local_coder_driver.py", region)
        self.assertIn("PROGRESS:", region)

    def test_the_code_style_index_lists_r39_and_the_new_range(self):
        index = flat(CODE_STYLE.read_text(encoding="utf-8"))
        self.assertIn("`R0` to `R39`", index)
        self.assertRegex(index, r"R38` and `R39` in `workflows.md`|R38 and R39 in `workflows.md`")

    def test_no_model_tag_appears_in_the_rule_or_the_agent(self):
        for label, text in (("rule", r39(self.workflows)), ("export", export_region(self.claude)),
                            ("agent", AGENT.read_text(encoding="utf-8"))):
            with self.subTest(where=label):
                self.assertIsNone(MODEL_TAG.search(text), label)


class TestAgentIsALauncherAndAnAuditor(unittest.TestCase):
    def setUp(self):
        self.text = AGENT.read_text(encoding="utf-8")
        self.body = flat(self.text)

    def test_it_launches_the_driver_once_for_the_whole_ledger(self):
        for phrase in ("local_coder_driver.py", "PROGRESS:", "--progress", "once per plan",
                       "aider-setup", "PLAN:"):
            with self.subTest(phrase=phrase):
                self.assertIn(phrase, self.body)

    def test_it_audits_under_the_bounds_of_the_plan_header(self):
        for phrase in ("loop_bounds.py init --from-plan", "tick --findings", "code-review",
                       "security-review", "R35", "- [ ] audit:"):
            with self.subTest(phrase=phrase):
                self.assertIn(phrase, self.body)

    def test_it_audits_inside_the_sandbox_and_writes_findings_only_there(self):
        for phrase in ("--audit-begin", "--audit-end", "--sandbox", "only in the sandbox"):
            with self.subTest(phrase=phrase):
                self.assertIn(phrase, self.body)

    def test_it_carries_no_instruction_to_write_or_edit_code(self):
        self.assertEqual(edit_instructions(self.text), [])

    def test_it_sends_a_blocked_step_back_to_the_cloud_and_never_raises_a_bound(self):
        self.assertIn("[!]", self.body)
        self.assertIn("never raises a bound", self.body)

    def test_it_no_longer_generates_through_a_hand_built_prompt(self):
        self.assertNotIn("Assemble ONE self-contained prompt", self.body)
        self.assertNotIn("--verify", self.body)


class TestNoStaleWordingRemains(unittest.TestCase):
    def test_no_definition_or_chapter_keeps_the_retired_wording(self):
        sources = {
            "workflows.md": WORKFLOWS, "CLAUDE.md": CLAUDE_MD, "agent": AGENT,
            "chapter 11": CHAPTER, "chapter 05": AGENTS_CHAPTER, "chapter 14": AIDER_CHAPTER,
            "loop-engineer": LOOP_SKILL,
        }
        for label, path in sources.items():
            with self.subTest(where=label):
                self.assertEqual(stale_phrases(path.read_text(encoding="utf-8")), [])


