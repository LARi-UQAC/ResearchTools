# Privacy guard, shared shell function - installed by install-git-hooks.ps1, sourced by
# pre-commit and pre-push. Needs $here (the directory holding the installed hooks).
#
# privacy_extra_scan: reads a diff on stdin, runs privacy-extra.awk over it and reports
# FILE NAMES only, never a line or a term. Returns 1 when the commit or push must be
# refused, 0 otherwise.
#
# A missing awk program, or no deny list at all, is a quiet pass (R11): a machine with no
# list has nothing to check. Two states are NOT quiet, because they look like protection
# and are not: a list file that holds no usable term, and an awk run that fails (a bad
# regex typed into fixture-path-allow.txt, for instance). Both print one line on stderr and
# let the change through. No local check covers a commit made with --no-verify, a
# repository-local core.hooksPath or privacyguard.enabled=false, and the public CI cannot
# hold this machine-local list: the pre-push hook is the last local chokepoint, and past it
# only the betterleaks rules of the CI scan apply.
#
# Local configuration, none of it committed:
#   $here/private-terms.txt         generated by install-git-hooks.ps1 -TermsFrom
#   $here/private-terms.extra.txt   written by hand, never touched by the installer
#   $here/privacy-guard.conf        min_term_length, the default floor (one owner, R0)
#   git config privacyguard.minTermLength   overrides the floor
#   git config privacyguard.absolutePaths   off | warn (default) | refuse

# privacy_list_is_utf16: succeeds when a list file is UTF-16 (a BOM, or a NUL byte). PowerShell
# 5.1 `>>` and Notepad's "Unicode" write it; awk then reads NUL-separated letters that never
# match, yet the file would still count as a usable list.
privacy_list_is_utf16() {
    [ -f "$1" ] || return 1
    case "$(head -c 2 "$1" | od -An -tx1 | tr -d ' \n')" in fffe|feff) return 0 ;; esac
    tr -d '\000' < "$1" | cmp -s - "$1" && return 1
    return 0
}

privacy_extra_scan() {
    awk_file="$here/privacy-extra.awk"
    [ -f "$awk_file" ] || return 0
    terms_file="$here/private-terms.txt"
    extra_file="$here/private-terms.extra.txt"
    have_list=0
    { [ -f "$terms_file" ] || [ -f "$extra_file" ]; } && have_list=1
    for list in "$terms_file" "$extra_file"; do
        if privacy_list_is_utf16 "$list"; then
            echo "privacy guard: $(basename "$list") is UTF-16, its terms are NOT read: save it as UTF-8" >&2
            # A path no file can have: awk skips an unreadable list, so the file counts for nothing.
            [ "$list" = "$terms_file" ] && terms_file="$here/.unreadable" || extra_file="$here/.unreadable"
        fi
    done
    command -v awk >/dev/null 2>&1 || {
        [ $have_list -eq 1 ] && echo "privacy guard: awk not found, the deny list was NOT checked" >&2
        return 0
    }
    min_len=$(git config --get privacyguard.minTermLength 2>/dev/null)
    if [ -z "$min_len" ]; then
        min_len=$(sed -n 's/^min_term_length=\([0-9][0-9]*\).*/\1/p' "$here/privacy-guard.conf" 2>/dev/null | head -n 1)
    fi
    if [ -z "$min_len" ]; then
        # No floor anywhere: say which key is missing rather than inventing one (R3).
        echo "privacy guard: min_term_length missing from $here/privacy-guard.conf, deny-list scan could not run" >&2
        return 0
    fi
    path_mode=$(git config --get privacyguard.absolutePaths 2>/dev/null)
    [ -n "$path_mode" ] || path_mode=warn
    # Two passes over the same diff, so a typo in the hand-edited path allowlist (a regex awk
    # compiles only when a drive path appears) cannot also switch off the name check, which
    # needs none of it: pass 1 loads the deny list and no regex file, pass 2 loads the
    # allowlist and no terms.
    diff_text=$(cat)
    found=$(printf '%s\n' "$diff_text" | awk -v termfiles="$terms_file|$extra_file" \
                -v minlen="$min_len" -v pathmode=off -v allowfile="" -f "$awk_file") || {
        echo "privacy guard: deny-list scan could not run (awk failed, see its message above), this change was NOT checked against it" >&2
        return 0
    }
    path_found=""
    if [ "$path_mode" != "off" ]; then
        path_found=$(printf '%s\n' "$diff_text" | awk -v termfiles="" -v minlen="$min_len" -v pathmode="$path_mode" \
                -v allowfile="$here/fixture-path-allow.txt" -f "$awk_file") || {
            echo "privacy guard: absolute-path check could not run (awk failed, see its message above), paths were NOT checked; the name check above did run" >&2
            path_found=""
        }
    fi
    usable=$(printf '%s\n' "$found" | awk -F'\t' '$1=="N"{print $2}')
    if [ $have_list -eq 1 ] && [ "${usable:-0}" -eq 0 ]; then
        echo "privacy guard: the deny list holds no usable term (floor $min_len), nothing is checked against it" >&2
    fi
    refuse=0
    terms_in=$(printf '%s\n' "$found" | awk -F'\t' '$1=="T"{print $2}')
    paths_in=$(printf '%s\n' "$path_found" | awk -F'\t' '$1=="P"{print $2}')
    if [ -n "$terms_in" ]; then
        echo "privacy guard: a term of the private deny list appears in:" >&2
        printf '%s\n' "$terms_in" | sed 's/^/  /' >&2
        echo "privacy guard: remove it, or mark a deliberate line 'betterleaks:allow'." >&2
        if printf '%s\n' "$terms_in" | grep -q '(commit author '; then
            # No marker can sit in an Author line: the commit itself must change.
            echo "privacy guard: a commit author line cannot carry that marker, rewrite the author of the commit (git commit --amend --reset-author, or rebase) or remove the term from the list." >&2
        fi
        refuse=1
    fi
    if [ -n "$paths_in" ]; then
        echo "privacy guard: absolute drive path in a test or fixture, check it is not a real one:" >&2
        printf '%s\n' "$paths_in" | sed 's/^/  /' >&2
        echo "privacy guard: replace it with a fictitious root, list the root in fixture-path-allow.txt, or git config privacyguard.absolutePaths off." >&2
        [ "$path_mode" = "refuse" ] && refuse=1
    fi
    return $refuse
}
